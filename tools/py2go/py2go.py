#!/usr/bin/env python3
"""
py2go translates wafw00f's Python detection plugins into Go source for wafgo.

The upstream plugins are tiny, declarative functions built from five matcher
calls (matchHeader, matchCookie, matchContent, matchStatus, matchReason),
if-statements, `not`, `and`/`or` and boolean returns. This tool parses them
with Python's `ast` module (the plugin code is never executed) and emits one
Go file per plugin plus a generated priority list.

Usage:
    python3 -I tools/py2go/py2go.py <path-to-wafw00f-checkout> <output-dir>

Any construct the translator does not understand aborts generation, so a
silent mistranslation is not possible.
"""

import ast
import io
import os
import re
import sys
import tokenize

HEADER = '// Code generated by tools/py2go from upstream {src}; DO NOT EDIT.\n'

# matcher name -> (Go method, default value of the `attack` argument)
MATCHERS = {
    'matchHeader': ('MatchHeader', False),
    'matchCookie': ('MatchCookie', False),
    'matchContent': ('MatchContent', True),
    'matchStatus': ('MatchStatus', True),
    'matchReason': ('MatchReason', True),
}


class TranslateError(Exception):
    pass


def camel(name):
    parts = re.split(r'[_\W]+', name)
    return ''.join(p[:1].upper() + p[1:] for p in parts if p)


def go_string(s):
    """Return a Go string literal for s, preferring raw strings."""
    if '`' not in s and '\r' not in s:
        return '`' + s + '`'
    out = ['"']
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append('\\x%02x' % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return ''.join(out)


def py_regex_to_go(pattern):
    """Convert the few Python-only regex spellings to RE2 syntax."""
    # \Z (end of string) is spelled \z in RE2.
    pattern = re.sub(r'(?<!\\)((?:\\\\)*)\\Z', r'\1\\z', pattern)
    return pattern


class PluginTranslator:
    def __init__(self, plugin_id, source, src_label):
        self.id = plugin_id
        self.prefix = plugin_id[:1].lower() + camel(plugin_id)[1:]
        self.src_label = src_label
        self.source = source
        self.tree = ast.parse(source)
        self.patterns = {}  # python pattern -> go var name
        self.pattern_order = []
        self.helpers = {}
        self.comments = self._collect_comments()
        self.emitted_comments = set()

    def _collect_comments(self):
        comments = {}
        for tok in tokenize.generate_tokens(io.StringIO(self.source).readline):
            if tok.type == tokenize.COMMENT:
                comments[tok.start[0]] = tok.string.lstrip('#').strip()
        return comments

    def pattern_var(self, pattern):
        if pattern not in self.patterns:
            name = '%sRe%d' % (self.prefix, len(self.patterns))
            self.patterns[pattern] = name
            self.pattern_order.append(pattern)
        return self.patterns[pattern]

    def func_name(self, pyname):
        if pyname == 'is_waf':
            return 'is' + camel(self.id)
        return self.prefix + camel(pyname)

    # -- expressions ------------------------------------------------------
    def expr(self, node):
        if isinstance(node, ast.Constant) and isinstance(node.value, bool):
            return 'true' if node.value else 'false'
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not):
            inner = self.expr(node.operand)
            if isinstance(node.operand, ast.BoolOp):
                return '!(%s)' % inner
            return '!' + inner
        if isinstance(node, ast.BoolOp):
            op = ' && ' if isinstance(node.op, ast.And) else ' || '
            parts = []
            for v in node.values:
                s = self.expr(v)
                if isinstance(v, ast.BoolOp):
                    s = '(%s)' % s
                parts.append(s)
            return op.join(parts)
        if isinstance(node, ast.Call):
            return self.call(node)
        raise TranslateError('unsupported expression %s at line %d' % (ast.dump(node), node.lineno))

    def call(self, node):
        f = node.func
        # helper(self)
        if isinstance(f, ast.Name):
            if f.id not in self.helpers:
                raise TranslateError('call to unknown function %s' % f.id)
            if len(node.args) != 1 or not isinstance(node.args[0], ast.Name) or node.args[0].id != 'self':
                raise TranslateError('helper %s must be called as %s(self)' % (f.id, f.id))
            return '%s(m)' % self.func_name(f.id)
        # self.matchX(...)
        if not (isinstance(f, ast.Attribute) and isinstance(f.value, ast.Name) and f.value.id == 'self'):
            raise TranslateError('unsupported call %s' % ast.dump(node))
        if f.attr not in MATCHERS:
            raise TranslateError('unsupported matcher %s' % f.attr)
        method, attack = MATCHERS[f.attr]
        args = list(node.args)
        for kw in node.keywords:
            if kw.arg != 'attack':
                raise TranslateError('unsupported keyword %s' % kw.arg)
            attack = self.const(kw.value, bool)
        if f.attr == 'matchHeader':
            if len(args) == 2:
                attack = self.const(args.pop(), bool)
            if len(args) != 1 or not isinstance(args[0], ast.Tuple) or len(args[0].elts) != 2:
                raise TranslateError('matchHeader needs a (header, regex) tuple')
            header = self.const(args[0].elts[0], str)
            pattern = self.const(args[0].elts[1], str)
            goargs = '%s, %s' % (go_string(header), self.pattern_var(pattern))
        else:
            if len(args) == 2:
                attack = self.const(args.pop(), bool)
            if len(args) != 1:
                raise TranslateError('%s takes one argument' % f.attr)
            if f.attr == 'matchStatus':
                goargs = str(self.const(args[0], int))
            elif f.attr == 'matchReason':
                goargs = go_string(self.const(args[0], str))
            else:
                goargs = self.pattern_var(self.const(args[0], str))
        return 'm.%s(%s, %s)' % (method, goargs, 'true' if attack else 'false')

    @staticmethod
    def const(node, typ):
        if not isinstance(node, ast.Constant) or type(node.value) is not typ:
            raise TranslateError('expected %s constant, got %s' % (typ.__name__, ast.dump(node)))
        return node.value

    # -- statements -------------------------------------------------------
    def comments_before(self, lineno, indent, lo):
        out = []
        for ln in sorted(self.comments):
            if lo <= ln < lineno and ln not in self.emitted_comments:
                self.emitted_comments.add(ln)
                out.append('%s// %s' % (indent, self.comments[ln]) if self.comments[ln] else indent + '//')
        return out

    def stmts(self, body, depth, lo):
        indent = '\t' * depth
        out = []
        for st in body:
            out.extend(self.comments_before(st.lineno, indent, lo))
            if isinstance(st, ast.Expr) and isinstance(st.value, ast.Constant) and isinstance(st.value.value, str):
                for line in st.value.value.strip().splitlines():
                    out.append('%s// %s' % (indent, line.strip()))
            elif isinstance(st, ast.Return):
                if st.value is None:
                    raise TranslateError('bare return at line %d' % st.lineno)
                out.append('%sreturn %s' % (indent, self.expr(st.value)))
            elif isinstance(st, ast.If):
                out.append('%sif %s {' % (indent, self.expr(st.test)))
                out.extend(self.stmts(st.body, depth + 1, st.lineno))
                if st.orelse:
                    out.append('%s} else {' % indent)
                    out.extend(self.stmts(st.orelse, depth + 1, st.lineno))
                out.append('%s}' % indent)
            elif isinstance(st, ast.Pass):
                continue
            else:
                raise TranslateError('unsupported statement %s at line %d' % (type(st).__name__, st.lineno))
        return out

    def translate(self):
        name = None
        funcs = []
        for node in self.tree.body:
            if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant):
                continue  # module docstring / licence banner
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                continue
            if isinstance(node, ast.Assign) and len(node.targets) == 1 and \
                    isinstance(node.targets[0], ast.Name) and node.targets[0].id == 'NAME':
                name = self.const(node.value, str)
                continue
            if isinstance(node, ast.FunctionDef):
                if [a.arg for a in node.args.args] != ['self']:
                    raise TranslateError('function %s must take only self' % node.name)
                funcs.append(node)
                self.helpers[node.name] = node
                continue
            raise TranslateError('unsupported top-level %s' % type(node).__name__)
        if name is None:
            raise TranslateError('missing NAME')
        if 'is_waf' not in self.helpers:
            raise TranslateError('missing is_waf')

        bodies = []
        for fn in funcs:
            lines = ['func %s(m Matcher) bool {' % self.func_name(fn.name)]
            lines.extend(self.stmts(fn.body, 1, fn.lineno))
            # Python returns None (falsy) when falling off the end.
            if not fn.body or not isinstance(fn.body[-1], ast.Return):
                lines.append('\treturn false')
            lines.append('}')
            bodies.append('\n'.join(lines))

        out = [HEADER.format(src=self.src_label), '\npackage plugins\n']
        if self.pattern_order:
            out.append('\nvar (\n')
            for p in self.pattern_order:
                out.append('\t%s = rx(%s)\n' % (self.patterns[p], go_string(py_regex_to_go(p))))
            out.append(')\n')
        out.append('\nfunc init() {\n\tregister(%s, %s, %s)\n}\n' % (
            go_string(self.id), go_string(name), self.func_name('is_waf')))
        for b in bodies:
            out.append('\n' + b + '\n')
        return name, ''.join(out)


def parse_priority(path):
    tree = ast.parse(open(path, encoding='utf-8').read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and node.targets[0].id == 'wafdetectionsprio':
            return [PluginTranslator.const(e, str) for e in node.value.elts]
    raise TranslateError('wafdetectionsprio not found')


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    upstream, outdir = sys.argv[1], sys.argv[2]
    plugdir = os.path.join(upstream, 'wafw00f', 'plugins')

    # Remove previously generated files so deleted upstream plugins disappear.
    for fn in os.listdir(outdir):
        if fn.endswith('_gen.go'):
            os.remove(os.path.join(outdir, fn))

    names = []
    for fn in sorted(os.listdir(plugdir)):
        if not fn.endswith('.py') or fn == '__init__.py':
            continue
        pid = fn[:-3]
        src = open(os.path.join(plugdir, fn), encoding='utf-8').read()
        try:
            name, code = PluginTranslator(pid, src, 'wafw00f/plugins/' + fn).translate()
        except TranslateError as e:
            sys.exit('%s: %s' % (fn, e))
        names.append(name)
        with open(os.path.join(outdir, pid + '_gen.go'), 'w', encoding='utf-8') as f:
            f.write(code)

    prio = parse_priority(os.path.join(upstream, 'wafw00f', 'wafprio.py'))
    lines = [HEADER.format(src='wafw00f/wafprio.py'), '\npackage plugins\n\n',
             '// priority is the order in which upstream wafw00f runs its checks.\n',
             'var priority = []string{\n']
    lines.extend('\t%s,\n' % go_string(p) for p in prio)
    lines.append('}\n')
    with open(os.path.join(outdir, 'priority_gen.go'), 'w', encoding='utf-8') as f:
        f.write(''.join(lines))

    print('generated %d plugins, %d priority entries' % (len(names), len(prio)))


if __name__ == '__main__':
    main()
