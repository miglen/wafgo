#!/usr/bin/env python3
"""
nuclei2go converts the WAF matchers from projectdiscovery/nuclei-templates'
http/technologies/waf-detect.yaml into a Go source file of supplementary
wafgo signatures (plugins/nuclei_gen.go).

Each nuclei matcher becomes one Plugin registered under the "nuclei" source.
A matcher is a list of words/regexes joined by its `condition` (or/and) and
evaluated against a `part`:

    body     -> the response body           (MatchContent)
    header   -> the raw response headers    (MatchHeaderBlob)
    response -> status line + headers + body (MatchResponseBlob)

`word` matchers are case-sensitive literals (nw); `regex` matchers are used
verbatim (nx), since the upstream patterns already carry (?i) where wanted.

No external YAML dependency: the waf-detect file has a fixed, regular shape
and is parsed with a small hand-written reader. Run it with -I.

Usage:
    python3 -I tools/nuclei2go/nuclei2go.py <waf-detect.yaml> plugins/nuclei_gen.go
"""

import re
import sys

HEADER = ('// Code generated by tools/nuclei2go from projectdiscovery/'
          'nuclei-templates\n// (http/technologies/waf-detect.yaml, '
          'inspired by Ekultek/WhatWaf); DO NOT EDIT.\n')

