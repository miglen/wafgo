def pretty(slug):
    name = DISPLAY.get(slug) or re.sub(r'[_\-]+', ' ', slug).title()
    # Keep nuclei names as bare product names so they never collide with
    # wafw00f's "Product (Manufacturer)" spelling.
    return re.sub(r'\s*\([^)]*\)', '', name).strip()


def parse(text):
    """Return a list of matchers: {name, type, part, condition, patterns}."""
    lines = text.splitlines()
    matchers = []
    cur = None
    reading = None  # 'regex' or 'words'
    for raw in lines:
        s = raw.strip()
        if s.startswith('- type:'):
            if cur:
                matchers.append(cur)
            cur = {'type': s.split(':', 1)[1].strip(), 'part': 'response',
                   'condition': 'or', 'patterns': [], 'name': ''}
            reading = None
        elif cur is None:
            continue
        elif s.startswith('name:'):
            cur['name'] = s.split(':', 1)[1].strip()
        elif s.startswith('part:'):
            cur['part'] = s.split(':', 1)[1].strip()
        elif s.startswith('condition:'):
            cur['condition'] = s.split(':', 1)[1].strip()
        elif s in ('regex:', 'words:'):
            reading = s[:-1]
        elif s.startswith('- ') and reading:
            cur['patterns'].append(unquote(s[2:].strip()))
        elif s and not s.startswith('#') and not s.startswith('- '):
            # any other key ends a pattern list
            reading = None
    if cur:
        matchers.append(cur)
    # keep only real WAF matchers (skip the top info block if captured)
    return [m for m in matchers if m['name'] and m['patterns'] and m['type'] in ('regex', 'word')]


def unquote(v):
    if len(v) >= 2 and v[0] == v[-1] and v[0] in ('"', "'"):
        inner = v[1:-1]
        if v[0] == '"':
            inner = inner.encode().decode('unicode_escape')
        return inner
    return v


def go_raw(s):
    if '`' not in s and '\r' not in s:
        return '`' + s + '`'
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r') + '"'


PART_METHOD = {
    'body': ('MatchContent', True),
    'header': ('MatchHeaderBlob', True),
    'response': ('MatchResponseBlob', True),
}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    text = open(sys.argv[1], encoding='utf-8').read()
    matchers = parse(text)

    # Group matcher blocks that share a nuclei name (the file lists some WAFs,
    # e.g. safedog and stricthttp, as two blocks) into one signature.
    groups = {}
    order = []
    for m in matchers:
        key = pretty(m['name'])  # merge slugs that denote the same WAF
        if key not in groups:
            groups[key] = []
            order.append(key)
        groups[key].append(m)

    def block_expr(m):
        method, attack = PART_METHOD[m['part']]
        compile_fn = 'nx' if m['type'] == 'regex' else 'nw'
        cond = ' && ' if m['condition'] == 'and' else ' || '
        parts = ['m.%s(%s(%s), %s)' % (method, compile_fn, go_raw(p),
                                       'true' if attack else 'false')
                 for p in m['patterns']]
        expr = cond.join(parts)
        return '(%s)' % expr if len(parts) > 1 and m['condition'] == 'and' else expr

    used = set()
    out = [HEADER, '\npackage plugins\n\n', 'func init() {\n']
    bodies = []
    for name in order:
        base = re.sub(r'[^a-z0-9]', '', name.lower()) or 'waf'
        pid = 'nuclei_' + base
        while pid in used:
            pid += '_'
        used.add(pid)
        fn = 'nuclei' + ''.join(w.capitalize() for w in re.split(r'[^a-z0-9]+', pid)[1:] if w)
        blocks = [block_expr(m) for m in groups[name]]
        checks = ' ||\n\t\t'.join(blocks)
        out.append('\tregisterExtra(%s, %s, SourceNuclei, %s)\n' %
                   (go_raw(pid), go_raw(name), fn))
        bodies.append('func %s(m Matcher) bool {\n\treturn %s\n}\n' % (fn, checks))
    out.append('}\n\n')
    out.extend(b + '\n' for b in bodies)

    with open(sys.argv[2], 'w', encoding='utf-8') as f:
        f.write(''.join(out))
    print('generated %d nuclei signatures -> %s' % (len(matchers), sys.argv[2]))


if __name__ == '__main__':
    main()
